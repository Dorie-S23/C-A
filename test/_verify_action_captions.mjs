import assert from 'node:assert/strict';
import { actionCaption, createActionCaptions } from '../src/ui/actionCaptions.js';
import { preLevel1Dialogue } from '../src/data/dialogues.js';
const opening=elapsed=>({phase:'playing',elapsed});
assert.equal(actionCaption({opening:opening(0)}),'Snoring…');
assert.equal(actionCaption({opening:opening(4.99)}),'Snoring…');
for(const t of [5,5.22,5.44,5.6,6.7])assert.equal(actionCaption({opening:opening(t)}),'Knock, knock, knock.');
assert.equal(actionCaption({opening:opening(6.9)}),'');
assert.equal(actionCaption({opening:{phase:'seated',elapsed:8.1}}),'');
assert.equal(actionCaption({opening:{phase:'done',elapsed:0}}),'');
const jax=preLevel1Dialogue.find(n=>n.id==='jaxPassByText');
assert.equal(actionCaption({jaxPass:{active:true}}),jax.text);
assert.equal(jax.text,'Jax storms past.');
assert.equal(actionCaption({jaxPass:{active:false}}),'');
assert.equal(actionCaption({entrance:{phase:'entering',elapsed:1}}),'');
assert.equal(actionCaption({entrance:{phase:'exiting'}}),'');
assert.equal(actionCaption({entrance:{phase:'dialogue'}}),'');
const root={hidden:true,textContent:''},hud=createActionCaptions({root});
const playing={opening:opening(2)};hud.update(playing);assert.equal(root.hidden,false);
const caption=root.textContent;hud.update({...playing,hidden:true});assert.equal(root.hidden,true);
hud.update(playing);assert.equal(root.textContent,caption);
hud.update({});assert.equal(root.hidden,true);assert.equal(root.textContent,'');
console.log('PASS Minimal snoring/knocking/Jax captions, no entrance/departure narration, synchronized timing, pause/menu hiding, skip and cleanup');
